#!/usr/bin/env python3
"""Normalize various YouTube cookie formats into Netscape format for yt-dlp."""
import sys
import time


def is_netscape(text):
    first = next((ln for ln in text.splitlines() if ln.strip() and not ln.startswith("#")), "")
    return "\t" in first


def parse_json_cookies(text):
    import json
    data = json.loads(text)
    if isinstance(data, dict):
        data = data.get("cookies", [])
    rows = []
    for c in data:
        name = c.get("name", "")
        value = c.get("value", "")
        if not name:
            continue
        domain = c.get("domain", ".youtube.com")
        path = c.get("path", "/")
        expires = c.get("expires", -1)
        if expires is None or expires < 0:
            expires = int(time.time()) + 31536000
        rows.append(f"{domain}\tTRUE\t{path}\tTRUE\t{int(expires)}\t{name}\t{value}")
    return rows


def parse_header_string(text):
    rows = []
    expiry = int(time.time()) + 31536000
    for part in text.replace("\n", " ").split(";"):
        part = part.strip()
        if "=" not in part:
            continue
        name, value = part.split("=", 1)
        name, value = name.strip(), value.strip()
        if not name:
            continue
        rows.append(f".youtube.com\tTRUE\t/\tTRUE\t{expiry}\t{name}\t{value}")
    return rows


def parse_netscape(text):
    rows = []
    for ln in text.splitlines():
        ln = ln.rstrip("\n")
        if not ln.strip() or ln.startswith("#"):
            continue
        if ln.startswith("#HttpOnly_"):
            ln = ln[10:]
        fields = ln.split("\t")
        if len(fields) >= 7:
            rows.append("\t".join(fields[:7]))
    return rows


def main():
    path = "cookies.txt"
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        raw = f.read().strip()

    if not raw:
        print("cookies file is empty")
        return 1

    if is_netscape(raw):
        rows = parse_netscape(raw)
        kind = "Netscape"
    elif raw.lstrip().startswith(("[", "{")):
        rows = parse_json_cookies(raw)
        kind = "JSON"
    else:
        rows = parse_header_string(raw)
        kind = "header string"

    if not rows:
        print(f"no cookies parsed from {kind} input")
        return 1

    header = "# Netscape HTTP Cookie File\n# Generated by normalize_cookies.py\n\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(header + "\n".join(rows) + "\n")
    print(f"normalized {len(rows)} cookies from {kind} format")
    return 0


if __name__ == "__main__":
    sys.exit(main())
